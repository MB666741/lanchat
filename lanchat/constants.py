"""协议常量与默认配置。"""

from __future__ import annotations

# ---------------------------------------------------------------------------
# 协议版本: 握手双方必须一致, 否则拒绝连接
# ---------------------------------------------------------------------------
PROTOCOL_VERSION = 2

# 加密方案标识 (写进握手报文, 便于以后平滑升级)
CIPHER_SUITE = "X25519-ED25519-HKDF-SHA256-AES256GCM"

# ---------------------------------------------------------------------------
# 网络默认值
# ---------------------------------------------------------------------------
# 自动发现使用的 UDP 端口 (全网段广播, 所有实例监听同一端口以便互相看见)
DEFAULT_DISCOVERY_PORT = 50505
# TCP 聊天端口; 0 表示每次启动在下面那个宽范围里**随机挑一个空闲端口**
# (beacon 里会把真实端口广播给对方, 所以正常使用不需要固定)
DEFAULT_TCP_PORT = 0

# 没固定端口时, 自己在多大范围里随机挑:
# 不用系统的 bind(0) —— 它有两个毛病:
#   ① 只在"动态端口范围"里挑, 这段既窄又可以被人改小 (Windows 默认 49152~65535 共 16384 个;
#      本机实测 `netsh int ipv4 show dynamicport tcp` = 起始 1024、只有 13977 个);
#   ② 它是**顺序分配**的: 本机连开 30 次拿到 12994、12995、12996… 连号, 下一个端口等于白送。
# 这里改成在 1024~65535 (64512 个) 里随机试绑, 范围大得多, 顺序也打乱了。
# 随机试不到空闲端口时 (Hyper-V 保留段 / 杀软拦截) 自动退回系统分配, 绝不因此起不来。
RANDOM_TCP_PORT_RANGE = (1024, 65536)    # randrange 的上界不含 -> 最大 65535
RANDOM_TCP_PORT_TRIES = 12               # 随机试多少次

# 每 N 秒广播一次自己的 beacon
BEACON_INTERVAL = 3.0
# 超过该秒数没有收到某人的 beacon 就认为其离线
PEER_TIMEOUT = 12.0
# 连接失败后的重试冷却 (秒), 按失败次数递增
RECONNECT_DELAYS = (2.0, 4.0, 8.0, 15.0, 30.0)

# ---------------------------------------------------------------------------
# 会话与文件
# ---------------------------------------------------------------------------
NONCE_PREFIX_BYTES = 4               # 每条会话随机的 nonce 前缀 (避免 nonce 重用)
SESSION_ID_BYTES = 8                 # 会话标识长度
MAX_FRAME_BYTES = 8 * 1024 * 1024    # 单帧上限 (base64 之后的文件分片)
FILE_CHUNK_SIZE = 256 * 1024         # 文件分片明文大小
HEARTBEAT_INTERVAL = 30.0            # 心跳间隔 (秒)

# 握手 / 连接超时
HANDSHAKE_TIMEOUT = 10.0
CONNECT_TIMEOUT = 8.0

# ---------------------------------------------------------------------------
# 密钥轮换 (类似 TLS 的 KeyUpdate): 每收发多少条消息就重新协商一次会话密钥。
#
# 目的: 即使某个中间人日后破解出某一轮密钥, 也只能解开"那一小段"对话。
# 协议: 发起方发 begin(fresh) 后继续用旧密钥; 接收方收到 begin 立即切到新密钥,
#       并用旧密钥回一个 accept; 发起方收到 accept 再切 —— 配合"旧密钥宽限期",
#       在途消息不会丢 (tests/test_rekey.py 验证 40 条消息零丢失)。
# 自动轮换只由 peer_id 较小的一方发起 (两边同时发起会用各自的 fresh 派生出不同的密钥)。
# 设为 0 表示关闭。
# ---------------------------------------------------------------------------
REKEY_EVERY_MESSAGES = 30
REKEY_RETRY_SECONDS = 3.0            # 没收到回执时重发 begin 的间隔 (绝不单方面换密钥)

# "已解禁"通知 / "我同意加你"通知: 对方没确认收到 (…-ack) 之前, 每隔这么多秒重试一次
UNBLOCK_RETRY_SECONDS = 5.0
ACCEPT_RETRY_SECONDS = 5.0

# 加好友请求: 发出后对方没有任何回应 (连"收到"都没有) 就重发一次。
# 为什么需要: 两边同时发起连接时会话去重可能正好拆掉刚发请求的那条, 请求就悄悄丢了,
# 用户看到的只是"点了没反应"(报过)。有回执才能知道"到底送到没有"。
REQUEST_ACK_TIMEOUT = 5.0
REQUEST_MAX_RETRIES = 6

# 手动添加时的单播探测 (只填 IP, 自动问出对方的 TCP 端口): UDP 会丢包, 所以多问几次
PROBE_ATTEMPTS = 3
PROBE_TIMEOUT = 2.0                  # 每次尝试的等待窗口 (秒)

# 加好友验证问题: 答错多少次就自动封禁
DEFAULT_MAX_ANSWER_ATTEMPTS = 3
ANSWER_KDF_ITERATIONS = 200_000      # 答案哈希的 PBKDF2 迭代次数 (抬高离线爆破成本)
ANSWER_SALT_BYTES = 16
ANSWER_NONCE_BYTES = 32

# ---------------------------------------------------------------------------
# 会话内聊天记录 (只在内存里, 关掉程序就没了 —— 故意的, 不落盘)
# 作用: 对方重启/重连后把这期间的对话补发给他, 不让记录白白消失。
# ---------------------------------------------------------------------------
HISTORY_LIMIT = 500                  # 每个人最多保留最近多少条 (超出丢最旧的)
HISTORY_BATCH = 80                   # 一次补发最多多少条 (避免单帧过大)

# ---------------------------------------------------------------------------
# 长度混淆 (padding) + 压缩
# ---------------------------------------------------------------------------
# 密文长度 ≈ 明文长度。抓包的人虽然解不开, 但"这个包多大"本身就泄露信息:
# 几个字的闲聊 / 一大段历史补发 / 一个文件名, 大小完全不一样, 一眼能分类。
# 做法: 先按需压缩, 再补齐到 PAD_STEP 的"桶", **桶之上再随机插 0~一整个步长**,
# 于是同一条消息每次发送的大小都不一样, 而不是固定落在一个值上 (那本身就是指纹)。
# 代价: 每条小消息多传 ~1 KB (局域网无所谓); 文件分片那种大块不补。
PAD_ENABLED = True
PAD_STEP = 512                       # 桶大小 (字节)
PAD_RANDOM_EXTRA = True              # 桶之上再随机加 0~PAD_STEP-1 字节 (每次大小都不同)
PAD_MAX = 16384                      # 明文超过这个大小就不补 (补了也盖不住"很大"这件事)
PAD_HEADROOM = 64                    # 至少留一点余量, 免得正好压在桶边界上
COMPRESS_ENABLED = True              # 加密前先 zlib 压缩: 只在"确实更小"时才用
COMPRESS_MIN_BYTES = 48              # 太短的没必要压 (zlib 自身还有十几字节开销)
COMPRESS_MAX_BYTES = 65536           # 太大的一律不压 (文件分片已经是密/随机数据, 白费 CPU)
HISTORY_JITTER = (0.05, 0.25)        # 多帧补发之间的随机间隔 (秒): 别一发一大串

# ---------------------------------------------------------------------------
# 本机数据目录与文件名
# ---------------------------------------------------------------------------
APP_DIR_NAME = ".lanchat"
IDENTITY_FILE = "identity.json"      # 本机长期身份密钥 + 昵称
CONTACTS_FILE = "contacts.json"      # 好友 / 待处理请求 / 黑名单
SETTINGS_FILE = "settings.json"      # 界面偏好 (自动接收文件等)
DOWNLOAD_DIR_NAME = "lanchat_downloads"


def app_dir() -> str:
    """本机数据目录: ~/.lanchat"""
    import os

    path = os.path.join(os.path.expanduser("~"), APP_DIR_NAME)
    os.makedirs(path, exist_ok=True)
    return path
